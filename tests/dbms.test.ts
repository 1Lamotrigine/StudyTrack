import { test } from 'node:test';
import assert from 'node:assert/strict';
import { PGlite } from '@electric-sql/pglite';
import { initialize } from '../lib/db';
import { executeSql } from '../lib/dbms/execute';
import { readCatalog, readObject } from '../lib/dbms/catalog';
import { editData } from '../lib/dbms/edit';
import { splitStatements, validateScript } from '../lib/dbms/sql';
import { loadSnippets } from '../lib/dbms/snippets';
test('SQL lexer keeps function bodies, quoted names and nested comments intact', () => {
  const script = `-- query\nSELECT ';' AS semi; /* outer /* inner */ done */ CREATE FUNCTION x() RETURNS int LANGUAGE plpgsql AS $fn$ BEGIN RETURN 1; END; $fn$; SELECT "odd;name" FROM x;`;
  assert.equal(splitStatements(script).length, 3);
  assert.throws(() => validateScript('BEGIN; SELECT 1; COMMIT;', true));
  assert.throws(() => validateScript('\\gset'));
  assert.equal(validateScript("DO $$ BEGIN RAISE NOTICE 'COMMIT;'; END $$;", true).length, 1);
});
test('SQL workspace executes real queries, DDL, transactions, plans and metadata', async () => {
  const db = await initialize(new PGlite());
  try {
    let result = await executeSql(
      db,
      'SELECT 1 AS x, 2 AS x, NULL AS missing; SELECT count(*) FROM courses;',
    );
    assert.ok(!result.error, JSON.stringify(result.error));
    assert.equal(result.results.length, 2);
    assert.deepEqual(result.results[0].rows[0], ['1', '2', null]);
    assert.equal(result.results[0].fields[0].name, 'x');
    result = await executeSql(
      db,
      "CREATE TABLE public.console_demo(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note text NOT NULL); INSERT INTO public.console_demo(note) VALUES ('one'),('two'); SELECT * FROM public.console_demo ORDER BY id;",
    );
    assert.ok(!result.error, JSON.stringify(result.error));
    assert.equal(result.results.at(-1)?.rowCount, 2);
    result = await executeSql(
      db,
      "UPDATE public.console_demo SET note='preview'; SELECT * FROM public.console_demo;",
      'preview',
    );
    assert.ok(result.rolledBack);
    assert.equal(
      (await db.query<{ note: string }>('SELECT note FROM public.console_demo WHERE id=1')).rows[0]
        .note,
      'one',
    );
    result = await executeSql(
      db,
      "BEGIN; UPDATE public.console_demo SET note='commit' WHERE id=1; COMMIT;",
    );
    assert.ok(!result.error);
    assert.equal(
      (await db.query<{ note: string }>('SELECT note FROM public.console_demo WHERE id=1')).rows[0]
        .note,
      'commit',
    );
    result = await executeSql(db, "BEGIN; UPDATE public.console_demo SET note='unclosed';");
    assert.ok(result.rolledBack);
    assert.ok(!db.isInTransaction());
    assert.equal(
      (await db.query<{ note: string }>('SELECT note FROM public.console_demo WHERE id=1')).rows[0]
        .note,
      'commit',
    );
    result = await executeSql(db, 'SELECT definitely_missing FROM courses;');
    assert.equal(result.error?.code, '42703');
    assert.ok(result.error?.line);
    assert.ok(!db.isInTransaction());
    result = await executeSql(db, 'SELECT * FROM courses WHERE id=1', 'explain');
    assert.ok(!result.error);
    assert.ok(JSON.parse(result.results[0].rows[0][0]!)[0].Plan);
    result = await executeSql(db, 'SELECT * FROM generate_series(1,2200)');
    assert.equal(result.results[0].rows.length, 2000);
    assert.equal(result.results[0].rowCount, 2200);
    assert.ok(result.results[0].truncated);
    const catalog = await readCatalog(db);
    const object = catalog.objects.find((o) => o.name === 'console_demo' && o.kind === 'table')!;
    assert.ok(object);
    const details = await readObject(db, object.oid, 'table');
    assert.equal(details.columns.length, 2);
    assert.ok(details.columns[0].primary);
    assert.match(details.definition, /CREATE TABLE/);
    result = await executeSql(
      db,
      `DROP TABLE public.console_demo CASCADE; ${details.definition}`,
      'preview',
    );
    assert.ok(!result.error, 'Table DDL can be executed: ' + JSON.stringify(result.error));
    await editData(db, {
      operation: 'update',
      oid: object.oid,
      keys: { id: '1' },
      values: { note: 'edited' },
      original: { note: 'commit' },
    });
    await assert.rejects(
      editData(db, {
        operation: 'update',
        oid: object.oid,
        keys: { id: '1' },
        values: { note: 'lost update' },
        original: { note: 'commit' },
      }),
    );
    await editData(db, { operation: 'insert', oid: object.oid, values: { note: 'new row' } });
    await editData(db, { operation: 'delete', oid: object.oid, keys: { id: '2' } });
    const course = catalog.objects.find((o) => o.kind === 'table' && o.name === 'courses')!;
    const courseDdl = await readObject(db, course.oid, 'table');
    result = await executeSql(
      db,
      `DROP TABLE public.courses CASCADE; ${courseDdl.definition}`,
      'preview',
    );
    assert.ok(!result.error, 'Application DDL: ' + JSON.stringify(result.error));
    const fn = catalog.objects.find((o) => o.kind === 'function')!;
    assert.match((await readObject(db, fn.oid, 'function')).definition, /FUNCTION/);
    const snippets = await loadSnippets();
    assert.ok(snippets.some((s) => s.id === 'Q16'));
    assert.equal(snippets.filter((s) => /^Q/.test(s.id)).length, 16);
    for (const snippet of snippets.filter((s) => /^Q/.test(s.id))) {
      const r = await executeSql(db, snippet.sql);
      assert.ok(!r.error, snippet.id + ': ' + JSON.stringify(r.error));
    }
    result = await executeSql(db, snippets.find((s) => s.id === 'function')!.sql);
    assert.ok(!result.error, JSON.stringify(result.error));
    assert.ok(!db.isInTransaction());
  } finally {
    await db.close();
  }
});
